// Package macro implements Silk's opt-in, deterministic Go declaration/statement
// macros. It expands source text, never executes it. Output remains ordinary Go.
package macro

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/scanner"
	"go/token"
	"regexp"
	"strings"
	"unicode"

	"github.com/uk0/silk/diagnostic"
)

const Header = "// Code generated by silkgen -macro; DO NOT EDIT.\n"
const MaxSourceBytes = 1 << 20
const MaxOutputBytes = 4 << 20
const maxExpansions = 2048

type directive struct {
	start, end int
	kind, body string
	pos        token.Position
}
type definition struct {
	params []string
	body   string
}

var asciiParameter = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

var placeholder = regexp.MustCompile(`\$\{([A-Za-z_][A-Za-z0-9_]*)\}`)

// Expand accepts .silkgo source containing standalone //silk:macro Name(params),
// //silk:end, and //silk:expand Name(args) directives. Directives inside strings
// or block comments are inert. ${Param} is explicit textual substitution, also
// within identifiers/literals; this is not a hygienic or recursive macro system.
// Arguments must parse as Go expressions/types. Macro bodies may be defined
// after their use. Limits bound input, expansion count and output size.
func Expand(filename string, src []byte) ([]byte, error) {
	if len(src) > MaxSourceBytes {
		return nil, macroError(diagnostic.MacroLimit, token.Position{Filename: filename}, nil, "macro source exceeds %d bytes", MaxSourceBytes)
	}
	dirs, err := scanDirectives(filename, src)
	if err != nil {
		return nil, err
	}
	defs := map[string]definition{}
	var open *directive
	var params []string
	var name string
	// Removed definition intervals include their end directive and keep newlines.
	type span struct{ start, end int }
	var removed []span
	for n := range dirs {
		d := &dirs[n]
		switch d.kind {
		case "macro":
			if open != nil {
				return nil, macroError(diagnostic.MacroNesting, d.pos, nil, "nested macro definitions are not supported")
			}
			var err error
			name, params, err = parseCall(d.body, true)
			if err != nil {
				return nil, macroError(diagnostic.MacroDeclaration, d.pos, err, "invalid macro signature")
			}
			if _, exists := defs[name]; exists {
				return nil, macroError(diagnostic.MacroDuplicate, d.pos, nil, "duplicate macro %s", name)
			}
			open = d
		case "end":
			if open == nil || d.body != "" {
				return nil, macroError(diagnostic.MacroDirective, d.pos, nil, "unexpected silk:end")
			}
			body := string(src[open.end:d.start])
			allowed := map[string]bool{}
			for _, p := range params {
				allowed[p] = true
			}
			for _, m := range placeholder.FindAllStringSubmatchIndex(body, -1) {
				parameter := body[m[2]:m[3]]
				if !allowed[parameter] {
					return nil, diagnostic.New(diagnostic.MacroParameter, "unknown parameter "+parameter, nil).At(sourceLocation(filename, src, open.end+m[0]))
				}
			}
			defs[name] = definition{append([]string(nil), params...), body}
			removed = append(removed, span{open.start, d.end})
			open = nil
		case "expand":
			if open != nil {
				return nil, macroError(diagnostic.MacroNesting, d.pos, nil, "recursive/nested expansion is not supported")
			}
		default:
			return nil, macroError(diagnostic.MacroDirective, d.pos, nil, "unknown silk directive %q", d.kind)
		}
	}
	if open != nil {
		return nil, macroError(diagnostic.MacroUnclosed, open.pos, nil, "macro missing silk:end")
	}
	var out bytes.Buffer
	var origins originMap
	out.WriteString(Header)
	cursor, count, ri := 0, 0, 0
	for _, d := range dirs {
		if d.start < cursor {
			continue
		}
		if d.kind == "macro" {
			s := removed[ri]
			ri++
			origins.add(out.Len(), s.start-cursor, cursor, true)
			out.Write(src[cursor:s.start])
			out.WriteString(strings.Repeat("\n", bytes.Count(src[s.start:s.end], []byte{'\n'})))
			cursor = s.end
			continue
		}
		if d.kind != "expand" {
			continue
		}
		count++
		if count > maxExpansions {
			return nil, macroError(diagnostic.MacroLimit, d.pos, nil, "too many macro expansions")
		}
		n, args, err := parseCall(d.body, false)
		if err != nil {
			return nil, macroError(diagnostic.MacroDeclaration, d.pos, err, "invalid macro signature")
		}
		def, ok := defs[n]
		if !ok {
			return nil, macroError(diagnostic.MacroUnknown, d.pos, nil, "unknown macro %s", n)
		}
		if len(args) != len(def.params) {
			return nil, macroError(diagnostic.MacroArity, d.pos, nil, "%s expects %d arguments, got %d", n, len(def.params), len(args))
		}
		values := map[string]string{}
		for i, p := range def.params {
			values[p] = args[i]
		}
		// Preflight replacement growth before allocating a potentially large body.
		expandedSize := len(def.body)
		for _, m := range placeholder.FindAllStringSubmatch(def.body, -1) {
			expandedSize += len(values[m[1]]) - len(m[0])
			if expandedSize > MaxOutputBytes {
				return nil, macroError(diagnostic.MacroLimit, d.pos, nil, "expanded output exceeds limit")
			}
		}
		if out.Len()+d.start-cursor+expandedSize > MaxOutputBytes {
			return nil, macroError(diagnostic.MacroLimit, d.pos, nil, "expanded output exceeds limit")
		}
		origins.add(out.Len(), d.start-cursor, cursor, true)
		out.Write(src[cursor:d.start])
		expanded := placeholder.ReplaceAllStringFunc(def.body, func(s string) string { return values[s[2:len(s)-1]] })
		origins.add(out.Len(), len(expanded), d.pos.Offset, false)
		out.WriteString(expanded)
		cursor = d.end
	}
	if out.Len()+len(src)-cursor > MaxOutputBytes {
		return nil, macroError(diagnostic.MacroLimit, token.Position{Filename: filename}, nil, "expanded output exceeds limit")
	}
	origins.add(out.Len(), len(src)-cursor, cursor, true)
	out.Write(src[cursor:])
	// format.Source also accepts statement/declaration fragments. A generator
	// must publish a complete Go file, not silently accept inputs such as ";".
	if _, err := parser.ParseFile(token.NewFileSet(), filename, out.Bytes(), parser.AllErrors); err != nil {
		return nil, diagnostic.New(diagnostic.MacroGeneratedSyntax, "expanded Go is invalid", err).At(origins.errorLocation(filename, src, err))
	}
	result, err := format.Source(out.Bytes())
	if err != nil {
		return nil, diagnostic.New(diagnostic.MacroGeneratedSyntax, "expanded Go is invalid", err).At(origins.errorLocation(filename, src, err))
	}
	if len(result) > MaxOutputBytes {
		return nil, macroError(diagnostic.MacroLimit, token.Position{Filename: filename}, nil, "formatted output exceeds limit")
	}
	return result, nil
}
func parseCall(src string, parameters bool) (string, []string, error) {
	e, err := parser.ParseExpr(src)
	if err != nil {
		return "", nil, fmt.Errorf("expected Name(arguments): %w", err)
	}
	call, ok := e.(*ast.CallExpr)
	if !ok || call.Ellipsis.IsValid() {
		return "", nil, fmt.Errorf("expected non-variadic Name(arguments)")
	}
	id, ok := call.Fun.(*ast.Ident)
	if !ok || id.Name == "_" {
		return "", nil, fmt.Errorf("expected a macro identifier")
	}
	var args []string
	seen := map[string]bool{}
	for _, arg := range call.Args {
		if parameters {
			p, ok := arg.(*ast.Ident)
			if !ok || p.Name == "_" || !asciiParameter.MatchString(p.Name) || seen[p.Name] {
				return "", nil, fmt.Errorf("macro parameters must be distinct identifiers")
			}
			seen[p.Name] = true
			args = append(args, p.Name)
		} else {
			var b bytes.Buffer
			if err := format.Node(&b, token.NewFileSet(), arg); err != nil {
				return "", nil, err
			}
			args = append(args, b.String())
		}
	}
	return id.Name, args, nil
}

func scanDirectives(filename string, src []byte) ([]directive, error) {
	fset := token.NewFileSet()
	file := fset.AddFile(filename, -1, len(src))
	var scan scanner.Scanner
	// Placeholders are intentionally not valid Go before expansion. Final output
	// goes through the Go parser/gofmt; lexical errors are not silently published.
	scan.Init(file, src, func(token.Position, string) {}, scanner.ScanComments)
	var dirs []directive
	for {
		p, t, lit := scan.Scan()
		if t == token.EOF {
			break
		}
		if t != token.COMMENT || !strings.HasPrefix(lit, "//silk:") {
			continue
		}
		pos := file.PositionFor(p, false)
		off := pos.Offset
		lineStart := bytes.LastIndexByte(src[:off], '\n') + 1
		if strings.TrimSpace(string(src[lineStart:off])) != "" {
			return dirs, macroError(diagnostic.MacroDirective, pos, nil, "macro directive must occupy its own line")
		}
		// Read original comment bytes: scanner strips embedded CR, which would
		// shift source ranges and make navigation point at the wrong character.
		end := off
		for end < len(src) && src[end] != '\n' {
			end++
		}
		raw := strings.TrimSpace(strings.TrimPrefix(string(src[off:end]), "//silk:"))
		kind, body := raw, ""
		if n := strings.IndexFunc(raw, unicode.IsSpace); n >= 0 {
			kind, body = raw[:n], raw[n:]
		}
		kind = strings.TrimSpace(kind)
		body = strings.TrimSpace(body)
		dirs = append(dirs, directive{lineStart, end, kind, body, pos})
	}
	return dirs, nil
}
