package main

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/uk0/silk/core"
	"github.com/uk0/silk/decl"
	"github.com/uk0/silk/ged"
	"github.com/uk0/silk/internal/filetxn"
	"github.com/uk0/silk/internal/silkgen"
)

// regenerateCompanion keeps the existing generator's ownership and API. A
// typed SDK export must not silently become a decl.Node builder on IDE Save.
// New designs retain the established tree-builder API for compatibility.
func regenerateCompanion(silkuiPath string) error {
	doc, err := core.LoadTDocFile(silkuiPath)
	if err != nil {
		return fmt.Errorf("load: %w", err)
	}
	stem := strings.TrimSuffix(silkuiPath, ".silkui")
	machine, err := filetxn.Read(stem + ".silk.go")
	if err != nil {
		return err
	}
	packageName, err := companionPackage(filepath.Dir(silkuiPath))
	if err != nil {
		return err
	}
	source := string(machine.Bytes())
	if machine.Exists() && hasCompanionHeader(source, ged.GeneratedCodeHeader) {
		typeName, err := ged.SplitCodeType(source)
		if err != nil {
			return fmt.Errorf("%s: %w", machine.Path(), err)
		}
		// Auto-save must never synthesize a missing user file/main() behind the
		// developer's back. Explicit export is the recovery action for that case.
		user, err := filetxn.Read(stem + ".go")
		if err != nil {
			return err
		}
		if !user.Exists() {
			return fmt.Errorf("%s: split export has no user file; restore it or explicitly export to a new path", user.Path())
		}
		scene := ged.NewGedScene()
		if err := scene.LoadDesign(doc); err != nil {
			return err
		}
		if missing := scene.MissingWidgets(); len(missing) != 0 {
			return fmt.Errorf("cannot regenerate with missing widgets: %v", missing)
		}
		result, err := scene.GenerateCodeFile(machine.Path(), ged.CodeGenOptions{PackageName: packageName, TypeName: typeName})
		if err != nil {
			return err
		}
		if len(result.MissingImports) != 0 {
			return fmt.Errorf("generated files saved; add required imports to %s: %s", result.UserFile, strings.Join(result.MissingImports, ", "))
		}
		return nil
	}
	if machine.Exists() && !hasCompanionHeader(source, "// Code generated by silkgen — DO NOT EDIT.") {
		return fmt.Errorf("%s: refusing to replace a file not owned by silkgen", machine.Path())
	}
	tree, err := decl.FromTDoc(doc)
	if err != nil {
		return err
	}
	formatted, err := silkgen.GenerateSource(silkuiPath, packageName, "", tree)
	if err != nil {
		return err
	}
	return filetxn.Commit(filetxn.Change{Before: machine, Data: formatted})
}

// Generated files may be checked out with CRLF on Windows.
func hasCompanionHeader(source, header string) bool {
	line, _, _ := strings.Cut(source, "\n")
	return strings.TrimSuffix(line, "\r") == header
}
